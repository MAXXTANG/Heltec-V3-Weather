"""Original vector geometry rasterized for a 44 x 38 one-bit OLED icon area.

No enlargement of the old 24px icons. Each visible silhouette is centered after
rasterization; all ordinary contours use 2px round strokes at native resolution.
"""
from pathlib import Path
from PIL import Image, ImageDraw
import math

ROOT=Path(__file__).resolve().parents[1]
S=8
W,H=44,38

def canvas(): return Image.new('L',(48*S,48*S),0)
def scaled(points): return [(round(x*S),round(y*S)) for x,y in points]
def stroke(im,points,width=2,closed=False):
    draw=ImageDraw.Draw(im);p=scaled(points)
    if closed:p=p+[p[0]]
    draw.line(p,fill=255,width=round(width*S),joint='curve')
    r=width*S/2
    for x,y in p:
        draw.ellipse((x-r,y-r,x+r-1,y+r-1),fill=255)
def polygon(im,points,fill):ImageDraw.Draw(im).polygon(scaled(points),fill=fill)
def cubic(start,a,b,end,n=32):
    out=[]
    for i in range(1,n+1):
        t=i/n;u=1-t
        out.append((u*u*u*start[0]+3*u*u*t*a[0]+3*u*t*t*b[0]+t*t*t*end[0],
                    u*u*u*start[1]+3*u*u*t*a[1]+3*u*t*t*b[1]+t*t*t*end[1]))
    return out
def curve(start,segments):
    points=[start]
    for a,b,end in segments:points+=cubic(points[-1],a,b,end)
    return points
def transform(points,bounds,base=(3,8,41,32)):
    x0,y0,x1,y1=bounds;a,b,c,d=base
    return [(x0+(x-a)*(x1-x0)/(c-a),y0+(y-b)*(y1-y0)/(d-b)) for x,y in points]
def cloud(im,bounds=(3,10,41,34)):
    points=curve((11,32),[
        ((6,32),(3,29),(3,24)),((3,20),(6,17),(10,17)),
        ((11,11),(15,8),(21,8)),((27,8),(31,12),(32,17)),
        ((37,17),(41,20),(41,25)),((41,29),(38,32),(33,32))])
    points=transform(points,bounds)
    polygon(im,points,0);stroke(im,points,closed=True)
def sun(im,cx=23,cy=23,r=8,ray_start=12,ray_end=17):
    pts=[(cx+r*math.cos(t*math.pi/64),cy+r*math.sin(t*math.pi/64)) for t in range(128)]
    stroke(im,pts,closed=True)
    for i in range(8):
        a=i*math.pi/4
        stroke(im,[(cx+ray_start*math.cos(a),cy+ray_start*math.sin(a)),
                   (cx+ray_end*math.cos(a),cy+ray_end*math.sin(a))])
def moon(im,bounds=(8,6,37,40)):
    points=curve((27,6),[
        ((15,4),(7,13),(8,24)),((9,35),(19,41),(29,37)),
        ((34,35),(37,31),(38,26)),((27,29),(19,22),(20,14)),
        ((20,10),(23,7),(27,6))])
    points=transform(points,bounds,(7,4,38,41))
    polygon(im,points,0);stroke(im,points,closed=True)
def flake(im,cx,cy):
    for i in range(3):
        a=i*math.pi/3
        stroke(im,[(cx-4*math.cos(a),cy-4*math.sin(a)),(cx+4*math.cos(a),cy+4*math.sin(a))],1.7)
def make(name):
    im=canvas()
    if name=='sun':sun(im)
    elif name=='moon':moon(im)
    elif name=='partly':
        sun(im,14,13,5.5,8.5,11.5);cloud(im,(4,15,40,35))
    elif name=='partly_night':
        moon(im,(12,3,33,27));cloud(im,(4,16,40,35))
    elif name=='cloud':cloud(im)
    elif name=='fog':
        cloud(im,(4,7,40,27));stroke(im,[(8,32),(36,32)]);stroke(im,[(12,37),(32,37)])
    elif name in ('drizzle','rain','showers'):
        cloud(im,(4,6,40,27))
        if name=='drizzle':
            for x in (13,23,33):stroke(im,[(x,32),(x-1,34)])
        elif name=='rain':
            for x in (13,23,33):stroke(im,[(x,31),(x-3,37)])
        else:
            for x in (12,23,34):
                stroke(im,[(x,30),(x-1.5,33)]);stroke(im,[(x-3,36),(x-4.5,39)])
    elif name=='snow':
        cloud(im,(4,6,40,25));flake(im,15,33);flake(im,30,33)
    elif name=='storm':
        cloud(im,(4,5,40,25))
        polygon(im,[(22,28),(17,34),(22,34),(19,40),(30,31),(24,31),(27,28)],255)
    else:raise ValueError(name)
    # Retain proportions. Bound the ink, not the original drawing canvas.
    box=im.getbbox();im=im.crop(box)
    factor=min(1,(40*S)/im.width,(34*S)/im.height)
    if factor<1:im=im.resize((round(im.width*factor),round(im.height*factor)),Image.Resampling.LANCZOS)
    im=im.resize((max(1,round(im.width/S)),max(1,round(im.height/S))),Image.Resampling.LANCZOS)
    im=im.point(lambda p:255 if p>=128 else 0,'1').convert('L')
    im=im.crop(im.getbbox())
    result=Image.new('L',(W,H));result.paste(im,((W-im.width)//2,(H-im.height)//2))
    return result

names=('sun','moon','partly','partly_night','cloud','fog','drizzle','rain','showers','snow','storm')
out=ROOT/'build/native-icons';out.mkdir(parents=True,exist_ok=True)
header=['// Generated by tools/generate_weather_icons.py. Original 2px vector contours.',
        '#pragma once','struct WeatherIcon { const uint8_t *pixels; };',
        'static constexpr int WEATHER_ICON_WIDTH=44, WEATHER_ICON_HEIGHT=38;']
for name in names:
    im=make(name);im.save(out/f'{name}.png')
    box=im.getbbox();assert box
    assert abs(box[0]-(W-box[2]))<=1 and abs(box[1]-(H-box[3]))<=1
    assert box[0]>=2 and box[1]>=2 and box[2]<=W-2 and box[3]<=H-2
    data=[]
    for y in range(H):
        for xb in range((W+7)//8):
            byte=0
            for bit in range(8):
                x=xb*8+bit
                if x<W and im.getpixel((x,y)):byte|=0x80>>bit
            data.append(byte)
    header.append(f'static const uint8_t weather_{name}_pixels[] PROGMEM = {{')
    header += ['    '+','.join(f'0x{x:02x}' for x in data[i:i+24])+',' for i in range(0,len(data),24)]
    header.append('};')
    header.append(f'static const WeatherIcon weather_{name} = {{weather_{name}_pixels}};')
(ROOT/'src/weather_icons.h').write_text('\n'.join(header)+'\n')
print('Generated 11 centered native OLED icons (44 x 38).')
